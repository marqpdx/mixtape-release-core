# EXTRACTIVE SUMMARY
# ============================================================================

def extract_summary_simple(text: str, target_length: int = 400) -> str:
    """
    Simple extractive summarization using sentence position heuristics.

    Strategy:
    1. Split into sentences
    2. Weight by position (first paragraph > last paragraph > middle)
    3. Select top sentences until reaching target length
    4. Return in original order

    Args:
        text: Full document text
        target_length: Target character count (~300-500 recommended)

    Returns:
        Extractive summary (2-3 sentences from original text)
    """
    if not text or len(text.strip()) < 50:
        return ""

    # Split into sentences (simple regex, can be improved with nltk.sent_tokenize)
    sentences = re.split(r'(?<=[.!?])\s+', text)
    sentences = [s.strip() for s in sentences if len(s.strip()) > 20]

    if not sentences:
        return ""

    # If very short document, return first sentence
    if len(sentences) <= 2:
        return ' '.join(sentences[:2])

    # Score sentences by position
    scored_sentences = []
    num_sentences = len(sentences)

    for i, sentence in enumerate(sentences):
        # Position score (0-1, higher is better)
        if i < 3:
            # First 3 sentences (likely introduction)
            position_score = 1.0 - (i * 0.1)
        elif i >= num_sentences - 2:
            # Last 2 sentences (likely conclusion)
            position_score = 0.7
        else:
            # Middle sentences
            position_score = 0.5

        # Length penalty (avoid very short/very long sentences)
        length = len(sentence)
        if 50 <= length <= 150:
            length_score = 1.0
        elif length < 50:
            length_score = 0.6
        else:
            length_score = 0.8

        total_score = position_score * length_score
        scored_sentences.append((i, sentence, total_score))

    # Sort by score (descending) and select top sentences
    scored_sentences.sort(key=lambda x: x[2], reverse=True)

    # Select sentences until reaching target length
    selected_indices = []
    current_length = 0

    for idx, sentence, score in scored_sentences:
        if current_length + len(sentence) <= target_length:
            selected_indices.append(idx)
            current_length += len(sentence)

        if len(selected_indices) >= 3:  # Max 3 sentences
            break

    # Return in original order
    selected_indices.sort()
    selected_sentences = [sentences[i] for i in selected_indices]

    return ' '.join(selected_sentences)


