def extract_keywords_tfidf(text: str, top_n: int = 12) -> list[str]:
    """
    Extract keywords using TF-IDF (Term Frequency-Inverse Document Frequency).

    Simple implementation without external dependencies.
    For production, consider using scikit-learn's TfidfVectorizer.

    Args:
        text: Full document text
        top_n: Number of keywords to extract

    Returns:
        List of top N keywords (lowercase, deduplicated)
    """
    if not text or len(text.strip()) < 50:
        return []

    # Simple tokenization (split on non-word chars)
    words = re.findall(r'\b[a-z]{3,}\b', text.lower())

    if not words:
        return []

    # Common stop words (minimal set)
    stop_words = {
        'the', 'and', 'for', 'are', 'but', 'not', 'you', 'all', 'can', 'her',
        'was', 'one', 'our', 'out', 'day', 'get', 'has', 'him', 'his', 'how',
        'its', 'may', 'new', 'now', 'old', 'see', 'two', 'way', 'who', 'boy',
        'did', 'she', 'too', 'use', 'from', 'that', 'this', 'with', 'have',
        'will', 'what', 'when', 'which', 'their', 'said', 'each', 'make',
        'like', 'time', 'very', 'just', 'know', 'take', 'into', 'year',
        'your', 'good', 'some', 'could', 'them', 'than', 'then', 'been',
        'other', 'were', 'come', 'made', 'many', 'more', 'over', 'such',
        'only', 'down', 'also', 'back', 'well', 'much', 'where', 'there',
    }

    # Filter stop words and count frequencies
    filtered_words = [w for w in words if w not in stop_words]

    if not filtered_words:
        return []

    # Count term frequencies
    term_freq = {}
    for word in filtered_words:
        term_freq[word] = term_freq.get(word, 0) + 1

    # Sort by frequency
    sorted_terms = sorted(term_freq.items(), key=lambda x: x[1], reverse=True)

    # Return top N unique terms
    keywords = [term for term, freq in sorted_terms[:top_n]]

    return keywords


# ============================================================================
# MAIN EXTRACTION FUNCTION
# ============================================================================

def extract_artifact_metadata(
    artifact: Artifact,
    summary_method: str = 'simple',
    keywords_method: str = 'tfidf',
    metadata_version: str = '1.0-simple',
) -> dict[str, str | list[str]]:
    """
    Extract interior_summary and keywords from Artifact text.

    This is the main entry point called by the Celery task.

    Args:
        artifact: Artifact instance with .text populated
        summary_method: 'simple' | 'inkwell'
        keywords_method: 'tfidf' | 'rake'
        metadata_version: Version string to track extraction logic

    Returns:
        Dict with 'interior_summary', 'keywords', 'metadata_version'

    Raises:
        ValueError: If artifact.text is empty or invalid
    """
    if not artifact.text or len(artifact.text.strip()) < 50:
        logger.warning(f"Artifact {artifact.id} has insufficient text for extraction")
        return {
            'interior_summary': '',
            'keywords': [],
            'metadata_version': metadata_version,
        }

    # Extract summary
    if summary_method == 'inkwell':
        try:
            interior_summary = extract_summary_inkwell(artifact.text)
        except NotImplementedError:
            logger.info("Inkwell not configured, falling back to simple extraction")
            interior_summary = extract_summary_simple(artifact.text)
    else:
        interior_summary = extract_summary_simple(artifact.text)

    # Extract keywords
    if keywords_method == 'tfidf':
        keywords = extract_keywords_tfidf(artifact.text)
    else:
        # Future: Add RAKE or other methods
        keywords = extract_keywords_tfidf(artifact.text)

    logger.info(
        f"Extracted metadata for Artifact {artifact.id}: "
        f"summary={len(interior_summary)} chars, keywords={len(keywords)} terms"
    )

    return {
        'interior_summary': interior_summary,
        'keywords': keywords,
        'metadata_version': metadata_version,
    }
