"""
Metadata Extraction for Artifacts

Generates extractive summary and keywords from document text for Simple Search.
All extraction is non-editable and programmatically generated.

Design:
- interior_summary: 2-3 sentences (~300-500 chars) extracted from original text
- keywords: Top 12 terms/phrases extracted via TF-IDF or RAKE
- 100% extractive (preserves original words for high fidelity)
- No LLM required (fast, deterministic, no API costs)

Can be swapped to use Inkwell summarization if available.
"""

